def export_report(
    md_content: str,
    jurisdiction: str,
    framework: str,
    output_format: str,
    output_dir: str | None = None,
) -> str:
    """
    Exports a Markdown report to the specified format.

    Args:
        md_content: The Markdown report content.
        jurisdiction: e.g. "nist", "eu".
        framework: e.g. "csf", "gdpr".
        output_format: One of "html", "json", "txt", "docx", "pdf".
        output_dir: Output directory (defaults to REPORTS_DIR).

    Returns:
        Path to the exported file.
    """
    output_dir = output_dir or REPORTS_DIR
    os.makedirs(output_dir, exist_ok=True)
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    target_name = extract_target_entity_name(md_content, fallback=f"{jurisdiction}_{framework}")
    base_name = f"The_Audit_Report_of_{target_name}_{framework}_{timestamp}"

    if output_format == "pdf":
        out_path = os.path.join(output_dir, f"{base_name}.pdf")
        export_pdf(md_content, jurisdiction, framework, out_path)

    elif output_format == "docx":
        out_path = os.path.join(output_dir, f"{base_name}.docx")
        export_docx(md_content, jurisdiction, framework, out_path)

    elif output_format == "html":
        title = f"Compliance Report — {jurisdiction.upper()} / {framework.upper()}"
        body = markdown_to_html(md_content)
        content = HTML_TEMPLATE.format(
            title=html.escape(title),
            body=body,
            export_date=datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
        )
        out_path = os.path.join(output_dir, f"{base_name}.html")
        with open(out_path, "w", encoding="utf-8") as f:
            f.write(content)

    elif output_format == "json":
        data = markdown_to_json(md_content, jurisdiction, framework)
        out_path = os.path.join(output_dir, f"{base_name}.json")
        with open(out_path, "w", encoding="utf-8") as f:
            json.dump(data, f, indent=2, ensure_ascii=False)

    elif output_format == "txt":
        content = markdown_to_text(md_content)
        out_path = os.path.join(output_dir, f"{base_name}.txt")
        with open(out_path, "w", encoding="utf-8") as f:
            f.write(content)

    elif output_format == "docx":
        out_path = os.path.join(output_dir, f"{base_name}.docx")
        export_docx(md_content, jurisdiction, framework, out_path)

    else:
        raise ValueError(f"Unsupported format: '{output_format}'. Use 'html', 'json', 'txt', or 'docx'.")

    # Log export
    try:
        import pipeline_logger
        pipeline_logger.log_info(
            "report_export",
            f"Exported {output_format.upper()} report: {out_path}",
            extra={"format": output_format, "path": out_path},
        )
    except ImportError:
        pass

    return out_path


