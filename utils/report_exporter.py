def is_control_heading(line: str) -> bool:
    """Returns True if the line represents an actual control item header."""
    s = line.strip()
    if s.startswith(("🔹", "🔸", "#### 🔹", "### 🔹", "- 🔹", "* 🔹")):
        return True
    if s.startswith("#### `") or s.startswith("### `"):
        return True
    if s.startswith("#### ") and any(sep in s for sep in ["—", "–", " - "]):
        clean = strip_all_markdown_and_emojis(s).lower()
        if not any(k in clean for k in ["compliance breakdown", "scorecard", "summary", "action required"]):
            return True
    return False


def extract_canonical_control_id(raw_text: str) -> str:
    """
    STRICT CONTROL ID EXTRACTOR:
    Extracts ONLY the formal statutory or technical control identifier
    (e.g., Recital 91, Article 32, 34.3.a, 6.3.257, PR.AC-1, ID.GV-1, A.8.1, REQ-01, CWE-89).
    """
    cleaned = strip_all_markdown_and_emojis(raw_text).strip()
    
    if '—' in cleaned:
        cleaned = cleaned.split('—')[0].strip()
    elif '–' in cleaned:
        cleaned = cleaned.split('–')[0].strip()
    elif ':' in cleaned and not cleaned.lower().startswith(('http:', 'https:')):
        cleaned = cleaned.split(':')[0].strip()
        
    cleaned = cleaned.strip(' \t`*')
    
    patterns = [
        r'\b(NIST\s+SP\s+800-\d+\s+[A-Z]{2}-\d+)\b',
        r'\b(SP_800_63B_R4-REQ-\d+)\b',
        r'\b([A-Z]{2,4}\.[A-Z]{2,4}-\d+(?:\.\d+)?)\b',
        r'\b(Recital\s+\d+)\b',
        r'\b(Article\s+[\d\.]+(?:\([a-z0-9]+\))?)\b',
        r'\b(Art\.?\s*[\d\.]+(?:\([a-z0-9]+\))?)\b',
        r'\b(Preambule\.?\d*)\b',
        r'\b(WSTG-[A-Z]+-\d+)\b',
        r'\b([A-Z]\.\d+\.\d+(?:\.\d+)?)\b',
        r'\b(REQ-\d+)\b',
        r'\b(CWE-\d+)\b',
        r'\b(ASVS-[A-Za-z0-9\.\-]+)\b',
        r'\b(\d+\.\d+(?:\.[a-z0-9]+)?(?:\.[a-z0-9]+)?)\b',
        r'\b(GAP-\d+)\b',
        r'\b([A-Z]{2,4}-\d+)\b'
    ]
    for p in patterns:
        m = re.search(p, cleaned, re.IGNORECASE)
        if m:
            return m.group(1).strip()
    return cleaned[:30]


def extract_audit_findings_matrix(md_content: str, jurisdiction: str = "nist", framework: str = "csf") -> list[dict]:
    """
    Extracts structured findings into a canonical list of 6-field dictionaries:
    [control_id, title, status, rationale, remediation, priority]
    Handles section-grouped findings, runtime probes, markdown tables, and headings.
    """
    raw_lines = md_content.split('\n')
    findings = []

    # Strategy 1: Section-grouped Headings & Bullet items
    current_section_status = None
    lines = md_content.split('\n')
    i = 0
    while i < len(lines):
        line = lines[i].strip()
        clean_line = line.lstrip('#').strip().lower()
        
        is_section_header = (
            (line.startswith('#') or clean_line.endswith('controls:') or clean_line.endswith('controls'))
            and not clean_line.startswith(('*', '-', '•', '`', '🔹', '🔸'))
            and any(k in clean_line for k in ['control', 'matrix', 'finding', 'gap', 'scope', 'compliant'])
        )
        
        if is_section_header:
            if any(w in clean_line for w in ['not compliant', 'non-compliant', 'gaps / not compliant', 'gaps']):
                current_section_status = 'Not Compliant'
            elif any(w in clean_line for w in ['partially compliant', 'partial']):
                current_section_status = 'Partially Compliant'
            elif any(w in clean_line for w in ['fully compliant', 'compliant']) and not any(w in clean_line for w in ['not', 'non', 'gap']):
                current_section_status = 'Fully Compliant'
            elif any(w in clean_line for w in ['evaluated scope', 'not applicable', 'pre-implementation']):
                current_section_status = 'Not Applicable'

        if is_control_heading(line):
            raw_heading = re.sub(r'^[#\-\*\s🔹🔸]+', '', line).strip()
            cid = extract_canonical_control_id(raw_heading)
            
            # Extract title
            title_part = ''
            if '—' in raw_heading:
                title_part = raw_heading.split('—', 1)[1].strip()
            elif '–' in raw_heading:
                title_part = raw_heading.split('–', 1)[1].strip()
            elif ':' in raw_heading and not raw_heading.startswith(('http:', 'https:')):
                title_part = raw_heading.split(':', 1)[1].strip()
            else:
                title_part = raw_heading
            clean_title = strip_all_markdown_and_emojis(title_part)
            
            body_lines = []
            j = i + 1
            while j < len(lines):
                nxt = lines[j].strip()
                if is_control_heading(nxt) or (nxt.startswith(('### ', '## ')) and not nxt.startswith('####')) or nxt.startswith('---') or (nxt.lower().endswith('controls:') and any(k in nxt.lower() for k in ['compliant', 'gaps', 'not compliant'])):
                    break
                body_lines.append(nxt)
                j += 1
            body_text = '\n'.join(body_lines)

            # A control-level status is authoritative
            m_status = re.search(r'(?:^|\n)\s*(?:-\s*)?(?:\*\*)?Status(?:\*\*)?:\s*([^\n]+)', body_text, re.IGNORECASE)
            item_status = strip_all_markdown_and_emojis(m_status.group(1)) if m_status else (current_section_status or 'No Evidence Found')

            # Rationale extraction (supports both sub-bullets and multi-line plain text blocks)
            rationale_parts = []
            audit_bullets = re.findall(r'(?:^|\n)\s*(?:[-*]\s*)?(?:\*\*)?(?:Audit Finding|Control Requirement|Potential Risks|Technical Restrictions|Evidence & Scan Details|Auditor Explanation|Rationale|Detail)(?:\*\*)?:\s*([^\n]+)', body_text, re.IGNORECASE)
            if audit_bullets:
                rationale_parts.extend([strip_all_markdown_and_emojis(b) for b in audit_bullets if strip_all_markdown_and_emojis(b)])
            
            if not rationale_parts:
                m_exp = re.search(r'(?:^|\n)\s*(?:[-*]\s*)?(?:\*\*)?(?:Auditor Explanation|Rationale|Explanation|Detail)(?:\*\*)?:\s*([\s\S]+?)(?=\n\s*(?:-\s*)?(?:\*\*)?(?:Client Remediation|Remediation|Evidence Source|Status)|\Z)', body_text, re.IGNORECASE)
                if m_exp:
                    rationale_parts.append(strip_all_markdown_and_emojis(m_exp.group(1)))

            rationale = ' '.join(rationale_parts) if rationale_parts else f'Evaluated safeguard requirement for {clean_title}.'

            # Remediation extraction
            m_rem = re.search(r'(?:^|\n)\s*(?:[-*]\s*)?(?:\*\*)?(?:Client Remediation Plan|Recommended Remediation|Remediation|Recommendation)(?:\*\*)?:\s*([\s\S]+?)(?=\n\s*(?:-\s*)?(?:\*\*)?(?:Evidence Source|Status)|\Z)', body_text, re.IGNORECASE)
            if m_rem:
                rem_raw = m_rem.group(1).strip()
                rem_bullets = re.findall(r'\*\s*([^\n]+)', rem_raw)
                if rem_bullets:
                    remediation = ' '.join([strip_all_markdown_and_emojis(b) for b in rem_bullets if strip_all_markdown_and_emojis(b)])
                else:
                    remediation = strip_all_markdown_and_emojis(rem_raw)
            else:
                remediation = 'Maintain verified baseline.' if item_status == 'Fully Compliant' else 'Implement required safeguards to achieve compliance.'

            findings.append({
                'control_id': cid,
                'title': clean_title,
                'status': item_status,
                'rationale': rationale,
                'remediation': remediation
            })
            i = j - 1

        elif line.startswith(('- **', '* **')) and ('—' in line or '–' in line) and ':' in line:
            m_probe = re.match(r'^[-*]\s*\*\*([A-Za-z0-9_\.\-]+)\s*[—–-]\s*([^\*]+)\*\*:\s*([^\n]+)', line)
            if m_probe:
                p_cid = extract_canonical_control_id(m_probe.group(1))
                p_title = strip_all_markdown_and_emojis(m_probe.group(2))
                p_status_raw = m_probe.group(3).strip()
                status_val = 'Not Compliant' if 'fail' in p_status_raw.lower() else ('Untested' if any(w in p_status_raw.lower() for w in ['untested', 'nodata', 'no_data']) else 'Compliant')
                
                findings.append({
                    'control_id': p_cid,
                    'title': p_title,
                    'status': status_val,
                    'rationale': f'Runtime probe status: {strip_all_markdown_and_emojis(p_status_raw)}',
                    'remediation': 'Address dynamic probe finding.' if status_val != 'Compliant' else 'Probe passed.'
                })

        i += 1

    # Strategy 2: Table-based Findings Matrix
    if not findings:
        table_lines = [l.strip() for l in raw_lines if l.strip().startswith('|') and l.strip().endswith('|')]
        if len(table_lines) > 2:
            rows = [t for t in table_lines if not re.match(r'^\|[-:| ]+\|$', t)]
            if len(rows) > 1:
                header_cells = [c.strip().lower() for c in rows[0].split('|')[1:-1]]
                id_idx = next((idx_h for idx_h, h in enumerate(header_cells) if any(k in h for k in ['id', 'req', 'control'])), 0)
                title_idx = next((idx_h for idx_h, h in enumerate(header_cells) if any(k in h for k in ['design', 'title', 'requirement', 'description', 'name'])), 1 if len(header_cells) > 1 else 0)
                status_idx = next((idx_h for idx_h, h in enumerate(header_cells) if 'status' in h), -1)
                rem_idx = next((idx_h for idx_h, h in enumerate(header_cells) if any(k in h for k in ['remediation', 'action', 'recommendation'])), -1)

                for row in rows[1:]:
                    cells = [c.strip() for c in row.split('|')[1:-1]]
                    if len(cells) < 2:
                        continue
                    first_cell_clean = re.sub(r'[^\w\s]', '', cells[0]).strip().lower()
                    if any(first_cell_clean.startswith(w) for w in ['compliant', 'fully compliant', 'partially', 'not compliant', 'non compliant', 'not applicable', 'no evidence', 'total', 'control status', 'status', 'summary']):
                        continue

                    raw_id = cells[id_idx].strip() if id_idx < len(cells) else f"CTRL-{len(findings)+1}"
                    clean_id = extract_canonical_control_id(raw_id)
                    raw_title = strip_all_markdown_and_emojis(cells[title_idx]) if title_idx < len(cells) else "Security Requirement"
                    clean_title = re.sub(rf'^{re.escape(clean_id)}\s*[—–-]?\s*', '', raw_title, flags=re.IGNORECASE).strip() or raw_title
                    status_text = strip_all_markdown_and_emojis(cells[status_idx]) if (status_idx != -1 and status_idx < len(cells)) else "Evaluated"

                    st_low = status_text.lower()
                    rem_text = strip_all_markdown_and_emojis(cells[rem_idx]) if (rem_idx != -1 and rem_idx < len(cells)) else ("Implement missing safeguard controls to achieve full compliance." if "compliant" not in st_low or "not" in st_low else "Maintain verified operational baseline.")

                    findings.append({
                        "control_id": clean_id,
                        "title": clean_title,
                        "status": status_text,
                        "rationale": f"Evaluated compliance baseline for {clean_title}.",
                        "remediation": rem_text
                    })

    # Strategy 3: Standard ### Headings
    if not findings:
        finding_blocks = re.findall(r'#{2,4}\s*([A-Za-z0-9_\.\-]+(?:\s*—\s*[^\n]+)?)\s*\n([\s\S]+?)(?=\n#{2,4}|\n---|\Z)', md_content)
        for title_line, body in finding_blocks:
            if any(w in title_line.lower() for w in ['executive summary', 'summary of findings', 'recommendation', 'auditor sign-off', 'actionable', 'control mapping', 'summary']):
                continue
            raw_id = title_line.split('—')[0].strip() if '—' in title_line else title_line.strip()
            clean_id = extract_canonical_control_id(raw_id)
            raw_title = strip_all_markdown_and_emojis(title_line.split('—')[1].strip() if '—' in title_line else "Control Safeguard")

            status = "Compliant"
            m_st = re.search(r'-\s*\*\*Status\*\*:\s*([^\n]+)', body, re.IGNORECASE)
            if m_st:
                status = strip_all_markdown_and_emojis(m_st.group(1))

            rationale = "Safeguard controls evaluated against standard baseline."
            m_exp = re.search(r'-\s*\*\*(?:Rationale|Auditor Explanation|Details|Explanation):\*\*\s*([\s\S]+?)(?=\n\s*-\s*\*\*|\Z)', body, re.IGNORECASE)
            if m_exp:
                rationale = strip_all_markdown_and_emojis(m_exp.group(1))

            remediation = "Maintain verified baseline." if "Compliant" in status and "Not" not in status else "Implement required safeguards."
            m_rem = re.search(r'-\s*\*\*(?:Recommended remediation|Remediation|Recommendation|Client Remediation Plan):\*\*\s*([\s\S]+?)(?=\n\s*-\s*\*\*|\Z)', body, re.IGNORECASE)
            if m_rem:
                remediation = strip_all_markdown_and_emojis(m_rem.group(1))

            findings.append({
                "control_id": clean_id,
                "title": raw_title,
                "status": status,
                "rationale": rationale,
                "remediation": remediation
            })

    try:
        import report_sanitizer
        findings = report_sanitizer.sanitize_assessment_batch(findings, framework=f"{jurisdiction}/{framework}")
    except Exception:
        pass

    return findings


def build_comprehensive_executive_summary(md_content: str, detected_client: str, detected_fw: str, findings: list[dict]) -> str:
    """
    Constructs a rich, publication-grade Executive Summary synthesizing
    the audit scope, scorecard breakdown, and key operational observations.
    """
    m_exec = re.search(r'(?:#{1,4}\s*Executive Summary|\*\*Executive Summary\*\*)\s*\n+([\s\S]+?)(?:\n#{1,4}|\n---|\Z)', md_content, re.IGNORECASE)
    raw_summary = m_exec.group(1).strip() if m_exec else ""
    clean_summary = strip_all_markdown_and_emojis(raw_summary)

    # If the report already contains a detailed multi-sentence summary (> 140 chars), return it
    if len(clean_summary) > 140 and not clean_summary.startswith("Automated compliance assessment completed"):
        return clean_summary

    cnt_f = sum(1 for f in findings if 'Fully' in f.get('status', ''))
    cnt_p = sum(1 for f in findings if 'Partially' in f.get('status', ''))
    cnt_n = sum(1 for f in findings if 'Not' in f.get('status', ''))
    cnt_na = sum(1 for f in findings if any(k in f.get('status', '').lower() for k in ['applicable', 'untested', 'pre-implementation', 'design']))
    tot_assess = cnt_f + cnt_p + cnt_n
    
    pct_f = f"{(cnt_f / tot_assess * 100):.1f}%" if tot_assess > 0 else "0.0%"
    pct_gaps = f"{((cnt_p + cnt_n) / tot_assess * 100):.1f}%" if tot_assess > 0 else "0.0%"

    p1 = (
        f"This regulatory compliance audit conducted by the ComplianceMesh Multi-Agent Pipeline evaluated the technical evidence, "
        f"configuration architecture, and runtime security posture of {detected_client} against the {detected_fw} framework baseline. "
        f"The scope of assessment encompasses automated code inspection, authentication and authorization safeguards, data protection at rest, "
        f"and dynamic runtime probing."
    )
    p2 = (
        f"Across {tot_assess} assessable technical controls evaluated, {cnt_f} controls ({pct_f}) demonstrated verified compliance with established security criteria. "
        f"A total of {cnt_p + cnt_n} controls ({pct_gaps}) exhibited implementation gaps or insufficient technical evidence in the evaluated scope. "
        f"An additional {cnt_na} control items represent organizational governance, data protection agreements, or procedural workflows requiring administrative review."
    )
    p3 = (
        f"Remediation priorities include formalizing granular role-based authorization beyond administrative flags, enforcing comprehensive audit logging "
        f"for sensitive data operations, and verifying transport-layer encryption configurations. Following the engineering roadmap detailed in this report "
        f"will establish a defensible, audit-ready compliance posture."
    )

    return f"{p1}\n\n{p2}\n\n{p3}"


