def find_latest_report(jurisdiction: str, framework: str) -> str | None:
    """Finds the most recent Markdown report for the given jurisdiction/framework."""
    pattern = os.path.join(REPORTS_DIR, f"{jurisdiction}__{framework}_report_*.md")
    reports = sorted(glob.glob(pattern))
    if reports:
        return reports[-1]  # most recent by timestamp in filename
    return None


def strip_all_markdown_and_emojis(text: str) -> str:
    """
    Strips all emojis, decorative symbols, and markdown markup
    (e.g., **, *, `, #, list markers, [link](url)) from text.
    """
    if not text:
        return ""
    emoji_pattern = re.compile(
        r'[\U00010000-\U0010ffff]|[\u2600-\u27bf]|[\u2300-\u23ff]|[\u2b50-\u2b55]|[\u200d\ufe0f\u20e3]|'
        r'[✅⚠️❌⛔🔹🔸▪️•💻⚪🐙🔍📊📘📄📑📕]',
        flags=re.UNICODE
    )
    cleaned = emoji_pattern.sub('', text)
    cleaned = re.sub(r'\*{1,3}', '', cleaned)
    cleaned = re.sub(r'_{1,3}', '', cleaned)
    cleaned = re.sub(r'`+', '', cleaned)
    cleaned = re.sub(r'#{1,6}\s*', '', cleaned)
    cleaned = re.sub(r'\[([^\]]+)\]\([^\)]+\)', r'\1', cleaned)
    cleaned = re.sub(r'^\s*[-*•]\s*', '', cleaned)
    cleaned = re.sub(r'\s+', ' ', cleaned).strip()
    return cleaned


def extract_canonical_control_id(raw_text: str) -> str:
    """
    STRICT CONTROL ID EXTRACTOR:
    Extracts ONLY the formal statutory or technical control identifier
    (e.g., Recital 91, Article 32, 34.3.a, 6.3.257, PR.AC-1, ID.GV-1, A.8.1, REQ-01, CWE-89).
    """
    cleaned = strip_all_markdown_and_emojis(raw_text)
    
    if '—' in cleaned:
        cleaned = cleaned.split('—')[0].strip()
    elif '–' in cleaned:
        cleaned = cleaned.split('–')[0].strip()
    elif ':' in cleaned and not cleaned.lower().startswith('http'):
        cleaned = cleaned.split(':')[0].strip()
        
    cleaned = cleaned.strip(' \t')
    
    patterns = [
        r'\b(NIST\s+SP\s+800-\d+\s+[A-Z]{2}-\d+)\b',
        r'\b([A-Z]{2,4}\.[A-Z]{2,4}-\d+(?:\.\d+)?)\b',
        r'\b(Recital\s+\d+)\b',
        r'\b(Article\s+\d+(?:\.\d+)?(?:\([a-z0-9]+\))?)\b',
        r'\b(Art\.?\s*\d+(?:\.\d+)?(?:\([a-z0-9]+\))?)\b',
        r'\b([A-Z]\.\d+\.\d+(?:\.\d+)?)\b',
        r'\b(REQ-\d+)\b',
        r'\b(CWE-\d+)\b',
        r'\b(ASVS-\d+\.\d+(?:\.\d+)?)\b',
        r'\b(\d+\.\d+(?:\.[a-z0-9]+)?(?:\.[a-z0-9]+)?)\b',
        r'\b(GAP-\d+)\b',
        r'\b([A-Z]{2,4}-\d+)\b'
    ]
    for p in patterns:
        m = re.search(p, cleaned, re.IGNORECASE)
        if m:
            return m.group(1).strip()
    return cleaned[:25]


def extract_audit_findings_matrix(md_content: str, jurisdiction: str = "nist", framework: str = "csf") -> list[dict]:
    """
    Extracts structured findings into a canonical list of 6-field dictionaries:
    [control_id, title, status, rationale, remediation, priority]
    Handles section-grouped findings, runtime probes, markdown tables, and headings.
    """
    raw_lines = md_content.split('\n')
    norm_lines = []
    current_t_row = ""
    for r_line in raw_lines:
        s_line = r_line.strip()
        if not s_line:
            if current_t_row:
                norm_lines.append(current_t_row)
                current_t_row = ""
            continue
        if s_line.startswith('|'):
            if current_t_row:
                if current_t_row.count('|') >= 3 and current_t_row.endswith('|'):
                    norm_lines.append(current_t_row)
                    current_t_row = s_line
                else:
                    current_t_row += " " + s_line
            else:
                current_t_row = s_line
        elif current_t_row:
            current_t_row += " " + s_line
        else:
            norm_lines.append(s_line)
    if current_t_row:
        norm_lines.append(current_t_row)

    findings = []

    # Strategy 1: Section-grouped Headings
    current_section_status = None
    current_section_priority = None

    lines = md_content.split('\n')
    i = 0
    while i < len(lines):
        line = lines[i].strip()
        clean_line = line.lstrip('#').strip().lower()
        
        is_section_header = (
            (line.startswith('#') or clean_line.startswith(('✅', '⚠️', '❌', '⛔')))
            and not clean_line.startswith(('*', '-', '•', '`', '🔹', '🔸'))
            and any(k in clean_line for k in ['control', 'matrix', 'finding', 'gap', 'scope'])
        )
        
        if is_section_header:
            if any(w in clean_line for w in ['not compliant', 'non-compliant', 'gaps / not compliant', 'gaps']):
                current_section_status = 'Not Compliant'
                current_section_priority = 'High (P0)'
            elif any(w in clean_line for w in ['partially compliant', 'partial']):
                current_section_status = 'Partially Compliant'
                current_section_priority = 'Medium (P1)'
            elif any(w in clean_line for w in ['fully compliant', 'compliant']) and not any(w in clean_line for w in ['not', 'non', 'gap']):
                current_section_status = 'Fully Compliant'
                current_section_priority = 'Closed'
            elif any(w in clean_line for w in ['evaluated scope', 'not applicable', 'pre-implementation']):
                current_section_status = 'Not Applicable'
                current_section_priority = 'Low (P2)'

        if line.startswith('🔹') or (line.startswith('#### ') and ('🔹' in line or '—' in line or '–' in line)) or ((line.startswith('### ') or line.startswith('- **')) and current_section_status is not None and ('—' in line or '–' in line)):
            raw_heading = re.sub(r'^#{3,4}\s*', '', line).strip()
            if not any(k in raw_heading.lower() for k in ['credential & secret', 'dependency & cve', 'dynamic control inspection', 'compliance breakdown', 'summary', 'static security']):
                cid = extract_canonical_control_id(raw_heading)
                
                title_part = ''
                if '—' in raw_heading:
                    title_part = raw_heading.split('—', 1)[1].strip()
                elif '–' in raw_heading:
                    title_part = raw_heading.split('–', 1)[1].strip()
                elif '-' in raw_heading:
                    title_part = raw_heading.split('-', 1)[1].strip()
                else:
                    title_part = raw_heading
                clean_title = strip_all_markdown_and_emojis(title_part)

                body_lines = []
                j = i + 1
                while j < len(lines):
                    nxt = lines[j].strip()
                    if nxt.startswith('🔹') or nxt.startswith('#### ') or (nxt.startswith('### ') and not nxt.startswith('####')) or nxt.startswith('---') or any(w in nxt.lower() for w in ['fully compliant controls', 'partially compliant controls', 'not compliant controls', 'gaps / not compliant']):
                        break
                    body_lines.append(nxt)
                    j += 1
                body_text = '\n'.join(body_lines)

                m_audit = re.findall(r'(?:\*\*Audit Finding:\*\*|Audit Finding:|\*\*Auditor Explanation:\*\*|Auditor Explanation:|\*\*Technical Restrictions:\*\*|Technical Restrictions:|\*\*Control Requirement:\*\*|Control Requirement:)\s*([^\n]+)', body_text)
                if m_audit:
                    cleaned_chunks = [strip_all_markdown_and_emojis(chunk) for chunk in m_audit if strip_all_markdown_and_emojis(chunk)]
                    rationale = ' '.join(cleaned_chunks)
                else:
                    m_rat = re.search(r'-\s*\*\*(?:Rationale|Auditor Explanation|Details):\*\*\s*([^\n]+)', body_text, re.IGNORECASE)
                    rationale = strip_all_markdown_and_emojis(m_rat.group(1)) if m_rat else f'Evaluated safeguard requirement for {clean_title}.'

                m_rem = re.search(r'(?:\*\*Client Remediation Plan:\*\*|Client Remediation Plan:)\s*([\s\S]+?)(?=(?:\n\s*[-*]\s*\*\*Evidence Source:\*\*|\n\s*[-*]\s*\*\*|\n\s*####|\n\s*🔹|\n\s*###|\Z))', body_text, re.IGNORECASE)
                if m_rem:
                    remediation = strip_all_markdown_and_emojis(m_rem.group(1))
                else:
                    m_rem2 = re.search(r'(?:\*\*Recommended Remediation:\*\*|Recommended Remediation:|\*\*Remediation:\*\*|Remediation:)\s*([^\n]+)', body_text, re.IGNORECASE)
                    if m_rem2:
                        remediation = strip_all_markdown_and_emojis(m_rem2.group(1))
                    else:
                        remediation = 'Maintain verified baseline.' if current_section_status == 'Fully Compliant' else 'Implement required safeguards to achieve compliance.'

                findings.append({
                    'control_id': cid,
                    'title': clean_title,
                    'status': current_section_status or 'Compliant',
                    'rationale': rationale[:450],
                    'remediation': remediation[:450],
                    'priority': current_section_priority or 'Closed'
                })

        if line.startswith('- **') and ('—' in line or '–' in line) and ':' in line:
            m_probe = re.match(r'-\s*\*\*([A-Za-z0-9_\.\-]+)\s*[—–-]\s*([^\*]+)\*\*:\s*([^\n]+)', line)
            if m_probe:
                p_cid = extract_canonical_control_id(m_probe.group(1))
                p_title = strip_all_markdown_and_emojis(m_probe.group(2))
                p_status_raw = m_probe.group(3).strip()

                status_val = 'Not Compliant' if 'fail' in p_status_raw.lower() else ('Untested' if 'no_data' in p_status_raw.lower() else 'Compliant')
                prio_val = 'High (P0)' if status_val == 'Not Compliant' else ('Low (P2)' if status_val == 'Untested' else 'Closed')

                findings.append({
                    'control_id': p_cid,
                    'title': p_title,
                    'status': status_val,
                    'rationale': f'Runtime probe status: {strip_all_markdown_and_emojis(p_status_raw)}',
                    'remediation': 'Address dynamic probe finding.' if prio_val != 'Closed' else 'Probe passed.',
                    'priority': prio_val
                })

        i += 1

    # Strategy 2: Table-based Findings Matrix
    if not findings:
        table_lines = [l.strip() for l in norm_lines if l.strip().startswith('|') and l.strip().endswith('|')]
        if len(table_lines) > 2:
            rows = [t for t in table_lines if not re.match(r'^\|[-:| ]+\|$', t)]
            if len(rows) > 1:
                header_cells = [c.strip().lower() for c in rows[0].split('|')[1:-1]]
                id_idx = next((idx_h for idx_h, h in enumerate(header_cells) if any(k in h for k in ['id', 'req', 'control'])), 0)
                title_idx = next((idx_h for idx_h, h in enumerate(header_cells) if any(k in h for k in ['design', 'title', 'requirement', 'description', 'name'])), 1 if len(header_cells) > 1 else 0)
                status_idx = next((idx_h for idx_h, h in enumerate(header_cells) if 'status' in h), -1)
                rem_idx = next((idx_h for idx_h, h in enumerate(header_cells) if any(k in h for k in ['remediation', 'action', 'recommendation'])), -1)

                for row in rows[1:]:
                    cells = [c.strip() for c in row.split('|')[1:-1]]
                    if len(cells) < 2:
                        continue
                    first_cell_clean = re.sub(r'[^\w\s]', '', cells[0]).strip().lower()
                    if any(first_cell_clean.startswith(w) for w in ['compliant', 'fully compliant', 'partially', 'not compliant', 'non compliant', 'not applicable', 'no evidence', 'total', 'control status', 'status', 'summary']):
                        continue

                    raw_id = cells[id_idx].strip() if id_idx < len(cells) else f"CTRL-{len(findings)+1}"
                    clean_id = extract_canonical_control_id(raw_id)
                    raw_title = strip_all_markdown_and_emojis(cells[title_idx]) if title_idx < len(cells) else "Security Requirement"
                    clean_title = re.sub(rf'^{re.escape(clean_id)}\s*[—–-]?\s*', '', raw_title, flags=re.IGNORECASE).strip() or raw_title
                    status_text = strip_all_markdown_and_emojis(cells[status_idx]) if (status_idx != -1 and status_idx < len(cells)) else "Evaluated"

                    st_low = status_text.lower()
                    if any(w in st_low for w in ['not compliant', 'fail', 'gap']):
                        priority = "High (P0)"
                    elif any(w in st_low for w in ['partially', 'partial']):
                        priority = "Medium (P1)"
                    elif any(w in st_low for w in ['not applicable', 'pre-implementation', 'design only']):
                        priority = "Low (P2)"
                    else:
                        priority = "Closed"

                    rem_text = strip_all_markdown_and_emojis(cells[rem_idx]) if (rem_idx != -1 and rem_idx < len(cells)) else ("Implement missing safeguard controls to achieve full compliance." if priority != "Closed" else "Maintain verified operational baseline.")

                    findings.append({
                        "control_id": clean_id,
                        "title": clean_title,
                        "status": status_text,
                        "rationale": f"Evaluated compliance baseline for {clean_title}.",
                        "remediation": rem_text,
                        "priority": priority
                    })

    # Strategy 3: Standard ### Headings
    if not findings:
        finding_blocks = re.findall(r'#{2,4}\s*([A-Za-z0-9_\.\-]+(?:\s*—\s*[^\n]+)?)\s*\n([\s\S]+?)(?=\n#{2,4}|\n---|\Z)', md_content)
        for title_line, body in finding_blocks:
            if any(w in title_line.lower() for w in ['executive summary', 'summary of findings', 'recommendation', 'auditor sign-off', 'actionable', 'control mapping', 'summary']):
                continue
            raw_id = title_line.split('—')[0].strip() if '—' in title_line else title_line.strip()
            clean_id = extract_canonical_control_id(raw_id)
            raw_title = strip_all_markdown_and_emojis(title_line.split('—')[1].strip() if '—' in title_line else "Control Safeguard")

            status = "Compliant"
            m_st = re.search(r'-\s*\*\*Status\*\*:\s*([^\n]+)', body, re.IGNORECASE)
            if m_st:
                status = strip_all_markdown_and_emojis(m_st.group(1))

            rationale = "Safeguard controls evaluated against standard baseline."
            m_exp = re.search(r'-\s*\*\*(?:Rationale|Auditor Explanation|Details|Explanation)\*\*:\s*([^\n]+)', body, re.IGNORECASE)
            if m_exp:
                rationale = strip_all_markdown_and_emojis(m_exp.group(1))

            remediation = "Maintain verified baseline." if "Compliant" in status and "Not" not in status else "Implement required safeguards."
            m_rem = re.search(r'-\s*\*\*(?:Recommended remediation|Remediation|Recommendation)\*\*:\s*([^\n]+)', body, re.IGNORECASE)
            if m_rem:
                remediation = strip_all_markdown_and_emojis(m_rem.group(1))

            st_low = status.lower()
            if any(w in st_low for w in ['not compliant', 'fail']):
                priority = "High (P0)"
            elif any(w in st_low for w in ['partially', 'partial']):
                priority = "Medium (P1)"
            elif any(w in st_low for w in ['not applicable', 'untested']):
                priority = "Low (P2)"
            else:
                priority = "Closed"

            findings.append({
                "control_id": clean_id,
                "title": raw_title,
                "status": status,
                "rationale": rationale,
                "remediation": remediation,
                "priority": priority
            })

