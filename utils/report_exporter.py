def main():
    parser = argparse.ArgumentParser(description="Multi-Format Report Exporter")
    parser.add_argument(
        "--framework", required=True,
        help="Jurisdiction/framework slug, e.g. 'nist/csf' or 'eu/gdpr'"
    )
    parser.add_argument(
        "--format", required=True, choices=["html", "json", "txt", "all"],
        help="Output format: html, json, txt, or all"
    )
    parser.add_argument(
        "--input", default=None,
        help="Path to a specific Markdown report file (auto-detected if omitted)"
    )
    args = parser.parse_args()

    jurisdiction, framework = args.framework.split("/")

    if args.input:
        md_path = args.input
    else:
        md_path = find_latest_report(jurisdiction, framework)
        if not md_path:
            print(f"No Markdown report found for {jurisdiction}/{framework} in '{REPORTS_DIR}/'.")
            print("Run Agent 5 first, or specify --input path.")
            return

    print(f"Source report: {md_path}")
    with open(md_path, encoding="utf-8-sig") as f:
        md_content = f.read()

    formats = ["html", "json", "txt"] if args.format == "all" else [args.format]

    for fmt in formats:
        out_path = export_report(md_content, jurisdiction, framework, fmt)
        print(f"  Exported {fmt.upper():>4} → {out_path}")

    print("\nDone.")


if __name__ == "__main__":
    main()
