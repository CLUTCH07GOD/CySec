def markdown_to_json(md_content: str, jurisdiction: str, framework: str) -> dict:
    """
    Parses the Markdown report into a structured JSON representation.
    """
    sections = re.split(r"\n## ", md_content)

    result = {
        "jurisdiction": jurisdiction,
        "framework": framework,
        "export_format": "json",
        "exported_at": datetime.now().isoformat(),
        "sections": {},
    }

    for section in sections:
        lines = section.strip().split("\n")
        if not lines:
            continue
        title = lines[0].strip().lstrip("# ").strip()
        content = "\n".join(lines[1:]).strip()
        result["sections"][title] = content

    return result


# ---------------------------------------------------------------------------
# Markdown -> Plain Text
# ---------------------------------------------------------------------------
def markdown_to_text(md_content: str) -> str:
    """Strips Markdown formatting for plain-text email-friendly output."""
    text = md_content
    # Remove heading markers
    text = re.sub(r"^#{1,6}\s+", "", text, flags=re.MULTILINE)
    # Remove bold markers
    text = re.sub(r"\*\*(.+?)\*\*", r"\1", text)
    # Remove inline code markers
    text = re.sub(r"`(.+?)`", r"\1", text)
    # Remove table formatting (keep content)
    text = re.sub(r"^\|[-:|]+\|$", "", text, flags=re.MULTILINE)
    text = re.sub(r"\|", "  ", text)
    # Remove horizontal rules
    text = re.sub(r"^---+$", "-" * 60, text, flags=re.MULTILINE)
    return text.strip()


